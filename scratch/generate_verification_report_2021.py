import os
import psycopg2
import pandas as pd
from dotenv import load_dotenv

def generate_report():
    load_dotenv('.env')
    db_url = os.getenv('SUPABASE_DB_URL')
    if not db_url:
        print("SUPABASE_DB_URL not set.")
        return
        
    print("Connecting to Supabase...")
    conn = psycopg2.connect(db_url)
    cur = conn.cursor()
    
    print("Querying true database records...")
    query = """
        SELECT principal, snapshot_date, COUNT(DISTINCT sku_code) as sku_count
        FROM Inventory_Fact_Real
        WHERE is_demo = TRUE AND _src_file = 'Synthetic_Generator'
        GROUP BY principal, snapshot_date
        ORDER BY principal, snapshot_date
    """
    
    cur.execute(query)
    rows = cur.fetchall()
    
    df = pd.DataFrame(rows, columns=['principal', 'snapshot_date', 'sku_count'])
    df['year'] = pd.to_datetime(df['snapshot_date']).dt.year
    df['month'] = pd.to_datetime(df['snapshot_date']).dt.strftime('%B')
    
    years = [2021, 2022, 2023, 2024, 2025, 2026]
    months = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']
    
    markdown = "# Synthetic Inventory Verification Report (Jan 2021 - Jun 2026)\n\n"
    markdown += "This report was generated by querying Supabase directly for the exact row counts stored in the `Inventory_Fact_Real` table.\n\n"
    
    for principal in ['delmonte', 'unilever']:
        markdown += f"## {principal.upper()} Coverage\n\n"
        
        for year in years:
            markdown += f"### {year}\n"
            markdown += "| Month | DB Status | SKUs Populated (Real DB Count) |\n"
            markdown += "| :--- | :--- | :--- |\n"
            
            for month in months:
                match = df[(df['principal'] == principal) & (df['year'] == year) & (df['month'] == month)]
                
                if not match.empty:
                    count = match.iloc[0]['sku_count']
                    status = "✅ Found in Supabase"
                    markdown += f"| **{month}** | {status} | {count:,} SKUs |\n"
                else:
                    if year == 2026 and months.index(month) > 5:
                        status = "⚪ Future Month (Not Generated)"
                    else:
                        status = "❌ Missing in DB"
                    markdown += f"| **{month}** | {status} | 0 SKUs |\n"
                    
            markdown += "\n"
            
    with open('scratch/synthetic_verification_report_2021.md', 'w', encoding='utf-8') as f:
        f.write(markdown)
        
    print("Report generated successfully from Supabase.")
    conn.close()

if __name__ == '__main__':
    generate_report()
